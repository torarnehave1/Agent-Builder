/**
 * Build worker/components/vegvisr-fulltext.js from landing-page-template.js.
 *
 * The renderer (renderContent / renderFlexboxBlock / parseVegvisrElements) and the
 * "Vegvisr special element styles" CSS already exist inside LANDING_PAGE_TEMPLATE and are
 * the string-based implementation that avoids the regex/escaping failure mode. This script
 * lifts them out verbatim (evaluating the template literal, so no hand-unescaping) and wraps
 * them in a standalone component for delivery via api.vegvisr.org/components/.
 *
 * Run: node scripts/build-fulltext-component.mjs
 */
import { writeFileSync } from 'node:fs'
import { LANDING_PAGE_TEMPLATE as T } from '../landing-page-template.js'

function slice(startMark, endMark, what) {
  const a = T.indexOf(startMark)
  if (a === -1) throw new Error(`build failed: "${startMark}" not found in LANDING_PAGE_TEMPLATE (${what})`)
  const b = T.indexOf(endMark, a + startMark.length)
  if (b === -1) throw new Error(`build failed: "${endMark}" not found after "${startMark}" (${what})`)
  return T.slice(a, b).trimEnd()
}

const CSS = slice('/* Vegvisr special element styles */', '/* Mermaid diagram container */', 'css')
const RENDERER = slice('// ========== CONTENT RENDERER ==========', '// ========== VEGVISR ELEMENT PARSER ==========', 'renderContent')
  + '\n' + slice('function parseVegvisrElements(html) {', '\n    }\n', 'parseVegvisrElements') + '\n    }\n'

for (const [name, src] of [['renderContent', RENDERER], ['renderFlexboxBlock', RENDERER], ['parseVegvisrElements', RENDERER]]) {
  if (!src.includes('function ' + name)) throw new Error(`build failed: ${name} missing from extracted source`)
}
if (CSS.length < 2000) throw new Error(`build failed: CSS looks truncated (${CSS.length} chars)`)

const out = `/*!
 * vegvisr-fulltext.js — renders Vegvisr fulltext elements + markdown in any page.
 *
 * GENERATED by worker/scripts/build-fulltext-component.mjs from landing-page-template.js
 * (renderContent / renderFlexboxBlock / parseVegvisrElements + the "Vegvisr special element
 * styles" CSS). That implementation is string-based on purpose — hand-written regex versions
 * of this parser are what produced the "Invalid regular expression" failures.
 *
 * Delivery: stored as metadata.impl on the 'vegvisr-fulltext' node in the Component Registry
 * graph (4072b898-f111-42a9-b5ca-0d901bb17d26) and served verbatim by api-worker as
 * https://api.vegvisr.org/components/vegvisr-fulltext.js. A page carries ONE <script src>
 * line; editing the registry node updates every page with no republish.
 *
 * Dependencies: marked, loaded from https://api.vegvisr.org/components/marked.min.js
 * (own origin — no third-party CDN on published pages).
 *
 * API
 *   VegvisrFulltext.ready()                 -> Promise, resolves when marked is loaded
 *   VegvisrFulltext.render(markdown)        -> html string (throws if not ready)
 *   VegvisrFulltext.renderInto(el, md)      -> Promise, awaits ready then sets el.innerHTML
 *   <vegvisr-fulltext graph-id="..." node-id="...">   fetches the node and renders it
 *   <vegvisr-fulltext graph-id="..." node-label="..."> same, matched on label
 */
(function () {
  'use strict';
  if (window.VegvisrFulltext) return; // idempotent: a second <script src> is a no-op

  var MARKED_URL = 'https://api.vegvisr.org/components/marked.min.js';
  var KG_BASE = 'https://knowledge.vegvisr.org';
  var STYLE_ID = 'vegvisr-fulltext-styles';
  var LOG = '[vegvisr-fulltext]';

  var CSS = ${JSON.stringify(CSS)};

  function injectStyles() {
    if (document.getElementById(STYLE_ID)) return;
    var s = document.createElement('style');
    s.id = STYLE_ID;
    s.textContent = CSS;
    (document.head || document.documentElement).appendChild(s);
  }

  var markedReady = null;
  function ready() {
    if (markedReady) return markedReady;
    markedReady = new Promise(function (resolve, reject) {
      if (window.marked) { console.info(LOG, 'marked already present'); return resolve(window.marked); }
      var s = document.createElement('script');
      s.src = MARKED_URL;
      s.onload = function () {
        if (window.marked) { console.info(LOG, 'marked loaded from', MARKED_URL); resolve(window.marked); }
        else reject(new Error(MARKED_URL + ' loaded but window.marked is undefined'));
      };
      s.onerror = function () { reject(new Error('failed to load ' + MARKED_URL)); };
      (document.head || document.documentElement).appendChild(s);
    });
    markedReady.catch(function (e) { console.error(LOG, e.message); });
    return markedReady;
  }

  // ===== extracted verbatim from landing-page-template.js — do not hand-edit =====
${RENDERER.split('\n').map(l => '  ' + l).join('\n')}
  // ===== end extracted =====

  function render(raw) {
    if (!window.marked) throw new Error('VegvisrFulltext.render() called before marked loaded — await VegvisrFulltext.ready() first, or use renderInto().');
    injectStyles();
    return renderContent(String(raw == null ? '' : raw));
  }

  function renderInto(el, raw) {
    if (!el) return Promise.reject(new Error('renderInto(el, markdown): el is required'));
    return ready().then(function () {
      el.innerHTML = render(raw);
      return el;
    }).catch(function (e) {
      console.error(LOG, 'renderInto failed:', e.message);
      el.innerHTML = '<div class="vegvisr-fulltext-error" style="padding:12px;border-left:3px solid #c33;color:#c33;">' + LOG + ' ' + e.message + '</div>';
      throw e;
    });
  }

  function fetchNode(graphId, opts) {
    return fetch(KG_BASE + '/getknowgraph?id=' + encodeURIComponent(graphId))
      .then(function (r) {
        if (!r.ok) throw new Error('getknowgraph ' + graphId + ' -> HTTP ' + r.status);
        return r.json();
      })
      .then(function (g) {
        var nodes = (g && g.nodes) || [];
        var node = null;
        if (opts.nodeId) node = nodes.filter(function (n) { return n.id === opts.nodeId; })[0];
        else if (opts.nodeLabel) node = nodes.filter(function (n) { return String(n.label || '').trim() === opts.nodeLabel; })[0];
        else node = nodes.filter(function (n) { return n.type === 'fulltext'; })[0];
        if (!node) throw new Error('no matching node in graph ' + graphId + ' (' + JSON.stringify(opts) + '); graph has ' + nodes.length + ' node(s)');
        return node;
      });
  }

  if (window.customElements && !window.customElements.get('vegvisr-fulltext')) {
    window.customElements.define('vegvisr-fulltext', class extends HTMLElement {
      connectedCallback() {
        var el = this;
        var graphId = el.getAttribute('graph-id');
        var opts = { nodeId: el.getAttribute('node-id'), nodeLabel: el.getAttribute('node-label') };
        if (!graphId) {
          console.error(LOG, '<vegvisr-fulltext> needs a graph-id attribute');
          el.innerHTML = '<div style="padding:12px;color:#c33;">' + LOG + ' missing graph-id</div>';
          return;
        }
        el.innerHTML = '<div class="vegvisr-fulltext-loading" style="padding:12px;opacity:.6;">Laster…</div>';
        Promise.all([ready(), fetchNode(graphId, opts)])
          .then(function (r) {
            console.info(LOG, 'rendering node', r[1].id, 'from graph', graphId);
            el.innerHTML = render(r[1].info || '');
          })
          .catch(function (e) {
            console.error(LOG, e.message);
            el.innerHTML = '<div style="padding:12px;border-left:3px solid #c33;color:#c33;">' + LOG + ' ' + e.message + '</div>';
          });
      }
    });
  }

  window.VegvisrFulltext = { ready: ready, render: render, renderInto: renderInto, fetchNode: fetchNode, injectStyles: injectStyles };
  console.info(LOG, 'ready — VegvisrFulltext + <vegvisr-fulltext> registered');
})();
`

writeFileSync(new URL('../components/vegvisr-fulltext.js', import.meta.url), out)
console.log(`built components/vegvisr-fulltext.js — ${out.length} chars (renderer ${RENDERER.length}, css ${CSS.length})`)
